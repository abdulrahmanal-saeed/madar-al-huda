#!/usr/bin/env python3
"""Generate the mobile and hosted palette defaults from tokens.json."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'design/brand/tokens.json'
DART = ROOT / 'apps/mobile/lib/core/theme/brand_colors.dart'
PHP = ROOT / 'hosting/admin/palette-defaults.php'
CHROME_ROLES = ('heroStart', 'heroEnd', 'heroInk', 'splash')


def dart_color(value):
    alpha_rgb = value[1:] if len(value) == 9 else 'FF' + value[1:]
    return f'Color(0x{alpha_rgb})'


def dart_source(tokens):
    palettes = tokens['palettes']
    roles = [role for role in palettes['regular-light'] if role not in CHROME_ROLES]
    lines = [
        '// Generated by design/brand/generate_palette.py from tokens.json.',
        "import 'package:material_ui/material_ui.dart';",
        '',
        "import 'brand_palette.dart';",
        '',
        'abstract final class BrandColors {',
    ]
    for role, color in tokens['colors'].items():
        lines.append(f'  static const Color {role} = {dart_color(color)};')

    for mode in ('light', 'dark'):
        lines.extend(['', f'  static const {mode}Scheme = ColorScheme(',
                      f'    brightness: Brightness.{mode},'])
        for role in roles:
            lines.append(f"    {role}: {dart_color(palettes[f'regular-{mode}'][role])},")
        lines.append('  );')

    lines.extend(['', '  static const palettes = <String, Map<String, Color>>{'])
    for key, palette in palettes.items():
        lines.append(f"    '{key}': {{")
        for role, color in palette.items():
            lines.append(f"      '{role}': {dart_color(color)},")
        lines.append('    },')
    lines.append('  };')
    lines.extend(['', '  static const contrastPairs = ['])
    for foreground, background in tokens['paletteContrastPairs']:
        lines.append(f"    ('{foreground}', '{background}'),")
    lines.append('  ];')

    lines.extend(['', '  static BrandPalette fallback(String profile) =>',
                  '      resolve(profile, palettes[profile]!);'])
    lines.extend(['', '  static BrandPalette resolve(', '    String profile,',
                  '    Map<String, Color> colors', '  ) => BrandPalette(',
                  '    scheme: ColorScheme(',
                  "      brightness: profile.endsWith('-dark') ? Brightness.dark : Brightness.light,"])
    for role in roles:
        lines.append(f"      {role}: colors['{role}']!,")
    lines.extend(['    ),', '    chrome: BrandChrome('])
    for role in CHROME_ROLES:
        lines.append(f"      {role}: colors['{role}']!,")
    lines.extend(['    ),', '  );', '', '  static List<Color> beadShades(Color base) => [',
                  '    Color.lerp(base, Colors.white, .72)!,', '    base,',
                  '    Color.lerp(base, Colors.black, .35)!,', '  ];'])

    for name, paper in tokens['readingPapers'].items():
        lines.extend(['', f'  static const {name}ReadingPaper = ('])
        for role, value in paper.items():
            lines.append(f'    {role}: {dart_color(value)},')
        lines.append('  );')
    return '\n'.join([*lines, '}', ''])


def php_source(tokens):
    lines = [
        '<?php', 'declare(strict_types=1);', '',
        '// Generated by design/brand/generate_palette.py from tokens.json.',
        'const PALETTE_DEFAULTS = [',
    ]
    for key, palette in tokens['palettes'].items():
        lines.append(f"    '{key}' => [")
        for role, value in palette.items():
            lines.append(f"        '{role}' => '{value}',")
        lines.append('    ],')
    lines.extend(['];', '', 'const PALETTE_CONTRAST_PAIRS = ['])
    for foreground, background in tokens['paletteContrastPairs']:
        lines.append(f"    ['{foreground}', '{background}'],")
    lines.extend(['];', '', 'const PALETTE_LEGACY = ['])
    for role in ('primaryGreen', 'mutedGold', 'ivory', 'darkInk',
                 'legacyRamadanPrimary', 'legacyRamadanGold',
                 'legacyRamadanBackground', 'legacyRamadanInk', 'paper'):
        lines.append(f"    '{role}' => '{tokens['colors'][role]}',")
    return '\n'.join([*lines, '];', ''])


def native_sources(tokens):
    res = ROOT / 'apps/mobile/android/app/src/main/res'
    legacy = tokens['colors']
    shared = {
        'splash_background': tokens['palettes']['regular-light']['splash'],
        'ic_launcher_background': legacy['launcherBackground'],
        'prayer_widget_accent': legacy['goldBright'],
        'prayer_widget_text': legacy['ivory'],
        'prayer_widget_muted': legacy['widgetNeutral'],
        'prayer_widget_bg': legacy['primaryGreen'],
        'prayer_widget_border': legacy['mutedGold'],
    }
    for directory, colors in (
        ('values', shared),
        # The same baked launch image is used on Android before Flutter starts.
        ('values-night', {'splash_background': shared['splash_background']}),
    ):
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 '<!-- Generated by design/brand/generate_palette.py. -->', '<resources>']
        lines.extend(f'    <color name="{name}">{value}</color>' for name, value in colors.items())
        yield res / directory / 'colors.xml', '\n'.join([*lines, '</resources>', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tokens = json.loads(SOURCE.read_text(encoding='utf-8'))
    outputs = ((DART, dart_source(tokens)), (PHP, php_source(tokens)), *native_sources(tokens))
    for path, source in outputs:
        if args.check:
            actual = path.read_text(encoding='utf-8')
            # Dart's formatter may wrap expressions in this generated file.
            if path == DART:
                actual = ''.join(actual.split())
                source = ''.join(source.split())
            if actual != source:
                parser.error(f'{path.relative_to(ROOT)} is stale. Regenerate the palette.')
        else:
            path.write_text(source, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
